
-- Commerce Analytics Platform
-- Environment: DEV
-- Database: commerce_oltp_dev
-- Purpose: Create OLTP source schema

CREATE SCHEMA IF NOT EXISTS commerce;

-- 1. Customers
CREATE TABLE IF NOT EXISTS commerce.customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code VARCHAR(32) NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(255) UNIQUE,
    city VARCHAR(80),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Products
CREATE TABLE IF NOT EXISTS commerce.products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(40) NOT NULL UNIQUE,
    product_name VARCHAR(150) NOT NULL,
    category VARCHAR(80) NOT NULL,
    list_price_egp NUMERIC(12,2) NOT NULL
        CHECK (list_price_egp >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Orders
CREATE TABLE IF NOT EXISTS commerce.orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(40) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL
        REFERENCES commerce.customers(customer_id),
    order_status VARCHAR(20) NOT NULL
        CHECK (order_status IN (
            'CREATED', 'PAID', 'SHIPPED',
            'DELIVERED', 'CANCELLED'
        )),
    sales_channel VARCHAR(30) NOT NULL,
    order_date TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Order Items
CREATE TABLE IF NOT EXISTS commerce.order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL
        REFERENCES commerce.orders(order_id),
    product_id BIGINT NOT NULL
        REFERENCES commerce.products(product_id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price_egp NUMERIC(12,2) NOT NULL
        CHECK (unit_price_egp >= 0),
    discount_amount_egp NUMERIC(12,2) NOT NULL DEFAULT 0
        CHECK (discount_amount_egp >= 0)
);

-- 5. Payments
CREATE TABLE IF NOT EXISTS commerce.payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(60) NOT NULL UNIQUE,
    order_id BIGINT NOT NULL
        REFERENCES commerce.orders(order_id),
    payment_method VARCHAR(30) NOT NULL,
    payment_status VARCHAR(20) NOT NULL
        CHECK (payment_status IN (
            'PENDING', 'SUCCESS', 'FAILED', 'REFUNDED'
        )),
    amount_egp NUMERIC(12,2) NOT NULL
        CHECK (amount_egp >= 0),
    payment_date TIMESTAMPTZ
);
